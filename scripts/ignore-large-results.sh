#!/usr/bin/env bash
# Rewrites results/.gitignore so it lists every file under results/ that is
# larger than LIMIT_MB (default 5). Git has no "ignore by size" rule, so this
# keeps big generated outputs out of `git add results/`.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
limit_mb="${LIMIT_MB:-5}"
out="$repo_root/results/.gitignore"

{
    echo "# Generated by scripts/ignore-large-results.sh: files over ${limit_mb} MB."
    echo "# Re-run the script after producing new results; do not edit by hand."
    cd "$repo_root/results"
    # -size +NM means "more than N MiB" (rounded up), matching the hook's limit.
    find . -type f -size +"${limit_mb}"M ! -name .gitignore | sed 's|^\./|/|' | sort
} > "$out"

echo "Wrote $out ($(($(wc -l < "$out") - 2)) large file(s) ignored)."
