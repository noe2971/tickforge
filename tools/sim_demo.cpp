// sim_demo: the Step 3 demonstration run (PROGRESS.md, Rule L).
//
//   sim_demo <file.tfc> <output.md>
//
// JoinBestQuoter (100 shares, |inventory| < 500, post-only) on COLB and MSFT
// from 09:35:00 to 15:55:00 ET, for fill model {queue-aware, naive} x order
// latency {1 us, 100 us, 1 ms}, market-data latency 0, default fees. Every
// number written is measured from the run; nothing is estimated.

#include <cstdio>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

#include "tickforge/sim/simulator.hpp"
#include "tickforge/sim/strategies.hpp"

using namespace tickforge;
using namespace tickforge::sim;

namespace {

constexpr std::uint64_t kHour = 3'600'000'000'000ULL;
constexpr std::uint64_t kMinute = 60'000'000'000ULL;

std::string dollars(Micros m) {
    char b[48];
    std::snprintf(b, sizeof b, "%.2f", static_cast<double>(m) / 1e6);
    return b;
}
std::string num(std::uint64_t v) {
    std::string s = std::to_string(v);
    for (int i = static_cast<int>(s.size()) - 3; i > 0; i -= 3) s.insert(static_cast<std::size_t>(i), ",");
    return s;
}
std::string fixed(double v, int digits) {
    char b[48];
    std::snprintf(b, sizeof b, "%.*f", digits, v);
    return b;
}

struct Markout {
    double mid_sum = 0, px_sum = 0;  // share-weighted, $/share x shares
    std::uint64_t shares = 0, fills = 0;
};

struct Row {
    std::string symbol;
    FillModel model;
    std::uint64_t latency;
    SimResult r;
    Markout mk[3];
};

}  // namespace

int main(int argc, char** argv) {
    if (argc != 3) {
        std::cerr << "usage: sim_demo <file.tfc> <output.md>\n";
        return 2;
    }
    const std::string path = argv[1];
    std::vector<Row> rows;
    try {
        for (const char* sym : {"COLB", "MSFT"}) {
            for (FillModel model : {FillModel::queue_aware, FillModel::naive_touch}) {
                for (std::uint64_t lat : {1'000ULL, 100'000ULL, 1'000'000ULL}) {
                    SimConfig cfg;
                    cfg.symbol = sym;
                    cfg.model = model;
                    cfg.order_latency_ns = lat;
                    cfg.market_data_latency_ns = 0;
                    cfg.start_ns = 9 * kHour + 35 * kMinute;
                    cfg.end_ns = 15 * kHour + 55 * kMinute;
                    JoinBestQuoter strat(100, 500);
                    Row row{sym, model, lat, run_file(path, cfg, strat), {}};
                    for (const FillRecord& f : row.r.fills) {
                        for (std::size_t h = 0; h < 3; ++h) {
                            if (!f.markout_ok[h]) continue;
                            row.mk[h].mid_sum += f.markout(h) * f.report.qty;
                            row.mk[h].px_sum += f.markout_vs_price(h) * f.report.qty;
                            row.mk[h].shares += f.report.qty;
                            ++row.mk[h].fills;
                        }
                    }
                    std::cerr << sym << " " << (model == FillModel::queue_aware ? "queue" : "naive") << " " << lat
                              << " ns: " << row.r.stats.fills << " fills\n";
                    rows.push_back(std::move(row));
                }
            }
        }
    } catch (const std::exception& e) {
        std::cerr << "error: " << e.what() << "\n";
        return 1;
    }

    std::ofstream md(argv[2]);
    md << "# Step 3 demonstration run (Rule L)\n\n";
    md << "Input `" << path.substr(path.find_last_of('/') + 1) << "`, generated by `tools/sim_demo`. Strategy "
          "`JoinBestQuoter`: one 100-share post-only order at the best bid and one at the best ask (as the strategy "
          "sees them), replaced at the new best when that price changes; no buying at inventory >= +500, no selling at "
          "<= -500. 09:35:00 to 15:55:00 ET; at 15:55:00 every order is cancelled and P&L is marked at the midpoint "
          "(no flattening). Market-data latency 0; maker rebate $0.0020/share, taker fee $0.0030/share (illustrative "
          "defaults). All numbers are measured from the runs.\n\n";
    auto model_name = [](FillModel m) { return m == FillModel::queue_aware ? "queue-aware" : "naive"; };
    auto lat_name = [](std::uint64_t ns) {
        return ns >= 1'000'000 ? std::to_string(ns / 1'000'000) + " ms" : std::to_string(ns / 1'000) + " us";
    };
    md << "## Orders and fills\n\n";
    md << "| Stock | Model | Order latency | Orders sent | Accepted | Rejected (post-only) | Fills | Filled shares | "
          "Filled / accepted shares | Bought | Sold | Inventory range |\n"
          "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|\n";
    for (const Row& w : rows) {
        const SimStats& s = w.r.stats;
        md << "| " << w.symbol << " | " << model_name(w.model) << " | " << lat_name(w.latency) << " | "
           << num(s.orders_sent) << " | " << num(s.accepted) << " | "
           << num(s.rejected[static_cast<std::size_t>(Reject::post_only_would_cross)]) << " | " << num(s.fills) << " | "
           << num(s.filled_shares) << " | "
           << (s.placed_shares ? fixed(100.0 * static_cast<double>(s.filled_shares) / static_cast<double>(s.placed_shares), 2) + "%" : "-")
           << " | " << num(s.bought_shares) << " | " << num(s.sold_shares) << " | " << s.min_inventory << " to "
           << s.max_inventory << " |\n";
    }
    md << "\n## Money (dollars)\n\n";
    md << "| Stock | Model | Order latency | Cash | Inventory at 15:55 | Mid at 15:55 | Rebates | Fees | P&L at 15:55 |\n"
          "|---|---|---|---:|---:|---:|---:|---:|---:|\n";
    for (const Row& w : rows) {
        md << "| " << w.symbol << " | " << model_name(w.model) << " | " << lat_name(w.latency) << " | "
           << dollars(w.r.final_cash) << " | " << w.r.final_inventory << " | "
           << fixed(static_cast<double>(w.r.final_mid2) / 2e4, 4) << " | " << dollars(w.r.stats.rebates) << " | "
           << dollars(w.r.stats.fees_paid) << " | " << dollars(w.r.final_mtm) << " |\n";
    }
    md << "\n## Markouts (share-weighted mean, cents per share)\n\n";
    md << "Midpoint move = side sign x (mid after the horizon - mid just before the fill). Negative = the price moved "
          "against the fill (adverse selection). \"vs fill price\" = side sign x (mid after the horizon - fill price), "
          "which adds the half-spread earned.\n\n";
    md << "| Stock | Model | Order latency | 100 ms mid move | 1 s mid move | 10 s mid move | 100 ms vs fill price | 1 s "
          "vs fill price | 10 s vs fill price | Fills measured (100 ms / 1 s / 10 s) |\n"
          "|---|---|---|---:|---:|---:|---:|---:|---:|---|\n";
    for (const Row& w : rows) {
        md << "| " << w.symbol << " | " << model_name(w.model) << " | " << lat_name(w.latency) << " |";
        for (std::size_t h = 0; h < 3; ++h)
            md << " " << (w.mk[h].shares ? fixed(100.0 * w.mk[h].mid_sum / static_cast<double>(w.mk[h].shares), 3) : "-")
               << " |";
        for (std::size_t h = 0; h < 3; ++h)
            md << " " << (w.mk[h].shares ? fixed(100.0 * w.mk[h].px_sum / static_cast<double>(w.mk[h].shares), 3) : "-")
               << " |";
        md << " " << num(w.mk[0].fills) << " / " << num(w.mk[1].fills) << " / " << num(w.mk[2].fills) << " |\n";
    }
    md << "\n## Checks\n\n| Stock | Model | Order latency | Queue anomalies (exec / crossing add) | Look-ahead violations | "
          "`ahead` underflows |\n|---|---|---|---:|---:|---:|\n";
    for (const Row& w : rows) {
        const SimStats& s = w.r.stats;
        md << "| " << w.symbol << " | " << model_name(w.model) << " | " << lat_name(w.latency) << " | "
           << num(s.anomaly_exec_with_ahead) << " / " << num(s.anomaly_cross_add_with_ahead) << " | "
           << num(s.lookahead_violations) << " | " << num(s.ahead_underflow) << " |\n";
    }
    // Post-hoc (added after the first run, to explain hypothesis 2; not a
    // Rule L metric): what triggered each fill, and how far the fill price was
    // from the midpoint just before it.
    md << "\n## Post-hoc: what triggered the fills\n\n";
    md << "Added after the first run to look into hypothesis 2; descriptive only. Trigger: `E`/`C` = a real execution "
          "on the order's side; `A`/`F`/`U` = a real order arriving on the other side at a crossing price. \"Half-spread "
          "captured\" = share-weighted mean of side sign x (mid just before the fill - fill price).\n\n";
    md << "| Stock | Model | Order latency | E | C | A/F/U (crossing add) | P/Q (naive only) | Half-spread captured (cents) |\n"
          "|---|---|---|---:|---:|---:|---:|---:|\n";
    for (const Row& w : rows) {
        std::uint64_t e = 0, c = 0, a = 0, pq = 0, sh = 0;
        double cap = 0;
        for (const FillRecord& f : w.r.fills) {
            switch (f.trigger) {
                case 'E': ++e; break;
                case 'C': ++c; break;
                case 'A': case 'F': case 'U': ++a; break;
                case 'P': case 'Q': ++pq; break;
                default: break;
            }
            if (f.mid2_before != 0) {
                const double sign = f.report.side == Side::buy ? 1.0 : -1.0;
                cap += sign * (static_cast<double>(f.mid2_before) / 2.0 - static_cast<double>(f.report.price)) / 1e4 * f.report.qty;
                sh += f.report.qty;
            }
        }
        md << "| " << w.symbol << " | " << model_name(w.model) << " | " << lat_name(w.latency) << " | " << num(e) << " | "
           << num(c) << " | " << num(a) << " | " << num(pq) << " | " << (sh ? fixed(100.0 * cap / static_cast<double>(sh), 3) : "-")
           << " |\n";
    }
    std::cout << "wrote " << argv[2] << "\n";
    return 0;
}
