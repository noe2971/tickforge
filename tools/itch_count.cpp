// itch_count: full-day ITCH 5.0 message-count report.
//
//   itch_count <input.gz|input.itch|compact.tfc> [output_dir] [label]
//
// Streams the file once and writes, into output_dir (default "results"):
//   itch_<label>_counts_by_type.csv
//   itch_<label>_counts_by_symbol.csv
//   itch_<label>_counts.md          (human-readable summary)
// label defaults to the first 8 characters of the input file name (the date
// for Nasdaq sample files, e.g. 01302019).

#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <numeric>
#include <string>
#include <vector>

#include "tickforge/io/byte_source.hpp"
#include "tickforge/itch/compact_file.hpp"
#include "tickforge/itch/message_counter.hpp"
#include "tickforge/itch/stream.hpp"

namespace fs = std::filesystem;
using namespace tickforge;

namespace {

std::unique_ptr<io::ByteSource> open_input(const std::string& path) {
    if (path.size() > 4 && path.compare(path.size() - 4, 4, ".tfc") == 0)
        return std::make_unique<itch::CompactReader>(path);
    return io::open_byte_source(path);
}

std::string with_commas(std::uint64_t v) {
    std::string s = std::to_string(v);
    for (int i = static_cast<int>(s.size()) - 3; i > 0; i -= 3) s.insert(static_cast<std::size_t>(i), ",");
    return s;
}

std::uint64_t sum(const itch::MessageCounter::Counts& c) { return std::accumulate(c.begin(), c.end(), std::uint64_t{0}); }

void write_markdown(const fs::path& out, const std::string& input, const itch::MessageCounter& mc,
                    const itch::StreamStats& st) {
    std::ofstream md(out);
    md << "# ITCH 5.0 message counts — " << fs::path(input).filename().string() << "\n\n";
    md << "Generated by `tools/itch_count` from a single streaming pass over the file.\n\n";
    md << "| | |\n|---|---|\n";
    md << "| Messages | " << with_commas(st.messages) << " |\n";
    md << "| Uncompressed ITCH bytes (incl. 2-byte length prefixes) | " << with_commas(st.bytes) << " |\n";
    md << "| Symbols in Stock Directory | " << with_commas(mc.locates().size()) << " |\n";
    md << "| First message timestamp | " << itch::format_timestamp(mc.first_timestamp_ns()) << " |\n";
    md << "| Last message timestamp | " << itch::format_timestamp(mc.last_timestamp_ns()) << " |\n";
    md << "| Unknown message types | " << mc.unknown() << " |\n";
    md << "| Messages with wrong length for their type | " << mc.bad_length() << " |\n\n";

    md << "## By message type\n\n| Type | Name | Bytes | Count | % of messages |\n|---|---|---:|---:|---:|\n";
    std::vector<std::size_t> order(itch::kMessageTypes.size());
    std::iota(order.begin(), order.end(), 0);
    std::stable_sort(order.begin(), order.end(), [&](auto a, auto b) { return mc.by_type()[a] > mc.by_type()[b]; });
    for (auto i : order) {
        const auto& t = itch::kMessageTypes[i];
        char pct[32];
        std::snprintf(pct, sizeof pct, "%.3f", 100.0 * static_cast<double>(mc.by_type()[i]) / static_cast<double>(mc.total()));
        md << "| `" << t.type << "` | " << t.name << " | " << t.size << " | " << with_commas(mc.by_type()[i]) << " | "
           << pct << " |\n";
    }

    struct Row {
        std::uint16_t locate;
        std::uint64_t total;
    };
    std::vector<Row> rows;
    for (std::uint32_t loc = 1; loc < 65536; ++loc)
        if (mc.locates().known(static_cast<std::uint16_t>(loc)))
            rows.push_back({static_cast<std::uint16_t>(loc), sum(mc.for_locate(static_cast<std::uint16_t>(loc)))});
    std::stable_sort(rows.begin(), rows.end(), [](const Row& a, const Row& b) { return a.total > b.total; });

    auto idx = [](char t) { return static_cast<std::size_t>(itch::message_type_index(t)); };
    auto row_line = [&](std::size_t rank, const Row& r) {
        const auto& c = mc.for_locate(r.locate);
        md << "| " << rank << " | " << mc.locates().symbol(r.locate) << " | " << r.locate << " | "
           << mc.locates().directory(r.locate)->market_category << " | " << with_commas(r.total) << " | "
           << with_commas(c[idx('A')] + c[idx('F')]) << " | " << with_commas(c[idx('E')] + c[idx('C')]) << " | "
           << with_commas(c[idx('X')] + c[idx('D')]) << " | " << with_commas(c[idx('U')]) << " | "
           << with_commas(c[idx('P')]) << " |\n";
    };
    const char* head =
        "| Rank | Symbol | Locate | Mkt cat | Total | Adds (A+F) | Executions (E+C) | Cancels+Deletes (X+D) | "
        "Replaces (U) | Hidden trades (P) |\n|---:|---|---:|---|---:|---:|---:|---:|---:|---:|\n";

    md << "\n## Top 25 symbols by message count\n\n" << head;
    for (std::size_t i = 0; i < rows.size() && i < 25; ++i) row_line(i + 1, rows[i]);

    md << "\n## Project symbols\n\n" << head;
    for (const char* sym : {"AAPL", "MSFT", "INTC"}) {
        for (std::size_t i = 0; i < rows.size(); ++i)
            if (mc.locates().symbol(rows[i].locate) == sym) row_line(i + 1, rows[i]);
    }
    md << "\nFull per-symbol counts (every message type) are in the `_counts_by_symbol.csv` file next to this one.\n";
}

}  // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        std::cerr << "usage: itch_count <input> [output_dir] [label]\n";
        return 2;
    }
    const std::string input = argv[1];
    const fs::path out_dir = argc > 2 ? argv[2] : "results";
    const std::string label = argc > 3 ? argv[3] : fs::path(input).filename().string().substr(0, 8);

    try {
        auto src = open_input(input);
        itch::MessageCounter mc;
        const itch::StreamStats st = itch::parse_stream(*src, mc);

        fs::create_directories(out_dir);
        const std::string stem = "itch_" + label + "_counts";
        {
            std::ofstream f(out_dir / (stem + "_by_type.csv"));
            mc.write_by_type_csv(f);
        }
        {
            std::ofstream f(out_dir / (stem + "_by_symbol.csv"));
            mc.write_by_symbol_csv(f);
        }
        write_markdown(out_dir / (stem + ".md"), input, mc, st);

        std::cout << "messages: " << st.messages << "\nbytes: " << st.bytes << "\nsymbols: " << mc.locates().size()
                  << "\nunknown types: " << st.unknown_type << "\nbad lengths: " << st.bad_length << "\nwrote "
                  << (out_dir / (stem + "*")).string() << "\n";
        return (st.unknown_type == 0 && st.bad_length == 0) ? 0 : 1;
    } catch (const std::exception& e) {
        std::cerr << "itch_count: " << e.what() << "\n";
        return 1;
    }
}
